# Builds a video's timeline.js, page.html and README from its script and narration.
"""Builds a video's timeline.js (scene start times, lengths and word cues) and page.html.

Usage: python3 common/build.py <video folder>

The scenes, their acts, on-screen text and narration come from the video's script (the
Markdown file named in its video.json), so the script stays the one place they're written.
Word times come from transcripts/sceneNN.json when the narration has been aligned
(prepare.py); otherwise they're estimated from the narration's text at about 150 words a
minute, so frames can be drafted before anything is recorded.

video.json: {"script": "../../2-how-to-see-a-timeline.md", "look": "paper",
             "minDur": {"3": 9.5}, "hold": 3.0}
"""
import json, os, re, sys

LEAD, TAIL = 0.8, 1.0
COMMON = os.path.dirname(os.path.abspath(__file__))
norm = lambda w: re.sub(r"[^a-z0-9]", "", w.lower())


def parse_script(path):
    """The script's scenes: [{id, act, title, ost, vo}], in order."""
    md = open(path, encoding="utf-8").read()
    md = md.split("\n## Appendix", 1)[0]
    scenes, act = [], ""
    for block in re.split(r"\n(?=## ACT |### Scene )", md):
        m = re.match(r"## ACT (\d+) · ([^(\n]+)", block)
        if m:
            act = f"Act {m.group(1)} · {m.group(2).strip().title()}"
            continue
        m = re.match(r"### Scene (\d+) · [^·\n]+ · ([^\n]+)", block)
        if not m:
            continue
        ost = re.search(r'\*\*OST:\*\* "([^"]*)"', block)
        vo = re.search(r'\*\*VO:\*\*\s*\n"(.*?)"\s*(\n|$)', block, re.S)
        scenes.append(dict(id=int(m.group(1)), act=act, title=m.group(2).strip(),
                           ost=ost.group(1) if ost else "", vo=vo.group(1).strip() if vo else ""))
    return scenes


def aligned_words(folder, i):
    """Word times from whisper.cpp's transcript of the trimmed clip, or None."""
    path = os.path.join(folder, "transcripts", f"scene{i:02d}.json")
    if not os.path.exists(path):
        return None
    out = []
    for seg in json.load(open(path))["transcription"]:
        first = True
        for tok in seg["tokens"]:
            tx = tok["text"]
            if tx.startswith("[_") or "<|" in tx:
                continue
            t = tok.get("t_dtw", -1)
            t = t / 100 if t is not None and t >= 0 else tok["offsets"]["from"] / 1000
            # A word starts at a space, at a segment start, or after a sentence break or dash.
            brk = out and re.search(r"[.!?—-]$", out[-1][0]) and re.match(r"[A-Za-z]", tx)
            if tx.startswith(" ") or not out or first or brk:
                out.append([tx.strip(), t])
            else:
                out[-1][0] += tx
            first = False
    return [[norm(w), round(max(0, t), 2)] for w, t in out if norm(w)]


def estimated_words(vo):
    """Word times read at ~150 wpm, with pauses at punctuation; and the speech's length."""
    words, t = [], 0.0
    for w in vo.split():
        if norm(w):
            words.append([norm(w), round(t, 2)])
        t += 0.17 + 0.045 * len(norm(w))
        if re.search(r"[.!?]$", w):
            t += 0.35
        elif re.search(r"[,;:]$", w):
            t += 0.18
    return words, round(t, 3)


def read_tl(folder):
    """timeline.js's TL."""
    text = open(os.path.join(folder, "timeline.js")).read()
    return json.loads(re.search(r"var TL = (.*);\s*$", text, re.S).group(1))


# What each kind of file in a video's folder is, for its README.
ROLES = [
    ("anim.js", "The scenes: SCENES[n](lt, q) draws scene n at lt seconds into it; q(\"word\") is when that word is said."),
    ("video.json", "The video's settings: its script, its look, respellings for the scratch voice, and scenes held longer."),
    ("shots.json", "The shots of the real app this tour captures (capture.mjs): the sample, keyframed views and actions."),
    ("shots.mjs", "Writes shots.json from the camera path in anim.js and the narration's cues, so zooms follow a new recording."),
    ("shots.js", "Generated by capture.mjs: each captured shot's frame count, for the page."),
    ("timeline.js", "Generated by build.py: scene start times, lengths and word cues."),
    ("cuts.json", "Generated by prepare.py: where the speech starts and ends in each narration clip."),
    ("captions.srt", "Generated by captions.py: the captions, in the script's wording, timed from the narration."),
    ("transcripts/", "Generated by prepare.py: whisper.cpp's word timings for each trimmed clip."),
]


def write_readme(folder, cfg):
    """The folder's README: what the video is and what each file is for."""
    title = re.search(r"^# (.+)$", open(os.path.join(folder, cfg["script"]), encoding="utf-8").read(), re.M).group(1)
    title = re.sub(r"^OpenChronology — |: Script and Storyboard$|\. Script and Storyboard$", "", title)
    # captions.srt follows build.py (captions.py reads timeline.js), so it's listed whenever it will be.
    always = {"timeline.js", "captions.srt"}
    rows = [(n, d) for n, d in ROLES if n in always or os.path.exists(os.path.join(folder, n.rstrip("/")))]
    width = max(len(f"[`{n}`]({n}{'README.md' if n.endswith('/') else ''})") for n, _ in rows)
    dwidth = max(len(d) for _, d in rows)
    lines = [f"# {title}", "", f"The source for the video of [`{cfg['script'].split('/')[-1]}`]({cfg['script']}), in the **{cfg.get('look', 'paper')}** look. "
             "Build, narrate, render and encode it as [the pipeline's README](../README.md) describes. "
             "Narration, trimmed audio, captured shots, frames and the MP4 are not in git.", "", "## Contents", "",
             f"| {'File'.ljust(width)} | {'What it is for'.ljust(dwidth)} |", f"| {'-' * width} | {'-' * dwidth} |"]
    for n, d in rows:
        link = f"[`{n}`]({n}{'README.md' if n.endswith('/') else ''})"
        lines.append(f"| {link.ljust(width)} | {d.ljust(dwidth)} |")
    open(os.path.join(folder, "README.md"), "w").write("\n".join(lines) + "\n")


def main(folder):
    folder = os.path.abspath(folder)
    cfg = json.load(open(os.path.join(folder, "video.json")))
    scenes_md = parse_script(os.path.join(folder, cfg["script"]))
    cuts_path = os.path.join(folder, "cuts.json")
    cuts = json.load(open(cuts_path)) if os.path.exists(cuts_path) else {}
    min_dur = {int(k): v for k, v in cfg.get("minDur", {}).items()}
    scenes, t, estimated = [], 0.0, []
    for k, sc in enumerate(scenes_md):
        i, last = sc["id"], k == len(scenes_md) - 1
        words = aligned_words(folder, i) if str(i) in cuts else None
        if words is not None:
            a, b = cuts[str(i)]
            speech = b - a
        else:
            words, speech = estimated_words(sc["vo"])
            estimated.append(i)
        dur = max(LEAD + speech + TAIL, min_dur.get(i, 0)) + (cfg.get("hold", 3.0) if last else 0)
        scenes.append(dict(id=i, act=sc["act"], ost=sc["ost"], start=round(t, 3), dur=round(dur, 3),
                           voice=LEAD, speech=round(speech, 3), words=words, last=last))
        t += dur
    acts = []
    for sc in scenes:
        if not acts or acts[-1]["name"] != sc["act"]:
            acts.append(dict(name=sc["act"], start=sc["start"], end=sc["start"] + sc["dur"]))
        else:
            acts[-1]["end"] = sc["start"] + sc["dur"]
    tl = dict(scenes=scenes, acts=acts, total=round(t, 3), estimated=estimated)
    open(os.path.join(folder, "timeline.js"), "w").write(
        "// Generated by common/build.py from the script and the narration's alignment: scene timings and word cues.\n"
        "var TL = " + json.dumps(tl) + ";\n")
    write_readme(folder, cfg)
    shots = os.path.join(folder, "shots.js")
    page = ('<!doctype html><html><head><meta charset="utf-8">'
            '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Saira+Condensed:wght@500;600;700'
            '&family=IBM+Plex+Mono:wght@400;500;600&family=EB+Garamond:ital,wght@0,500;0,600;0,700;1,500&display=block">'
            '<style>html,body{margin:0;background:#000}svg{display:block;width:1920px;height:1080px}</style></head>'
            '<body><svg id="stage" viewBox="0 0 320 180" xmlns="http://www.w3.org/2000/svg" '
            'xmlns:xlink="http://www.w3.org/1999/xlink"></svg><script>\n'
            f"var LOOK = {json.dumps(cfg.get('look', 'paper'))};\n"
            + open(os.path.join(COMMON, "core.js")).read()
            + open(os.path.join(folder, "timeline.js")).read()
            + (open(shots).read() if os.path.exists(shots) else "")
            + open(os.path.join(folder, "anim.js")).read()
            + "\n</script></body></html>\n")
    open(os.path.join(folder, "page.html"), "w").write(page)
    print(os.path.basename(folder), "total", round(t, 1), "s;", len(scenes), "scenes",
          f"(timing estimated for scenes {estimated})" if estimated else "")
    for sc in scenes:
        print(" ", sc["id"], sc["start"], sc["dur"])


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
